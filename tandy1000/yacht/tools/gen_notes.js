// Writes src/notes.inc: note constants plus SN76496 divider table.
// The chip runs at 3579545 Hz / 32. Its 10-bit divider bottoms out near A2.
const fs = require('fs');
const names = ['C','Cs','D','Ds','E','F','Fs','G','Gs','A','As','B'];
let eq = '', tbl = 'notes_tbl:\n    dw 0\n';
let idx = 1;
for (let midi = 45; midi <= 86; midi++) {
  const f = 440 * Math.pow(2, (midi - 69) / 12);
  const n = Math.round(3579545 / (32 * f));
  if (n > 1023) throw new Error('divider overflow at ' + midi);
  const name = names[midi % 12] + (Math.floor(midi / 12) - 1);
  eq += `N_${name} equ ${idx}\n`;
  tbl += `    dw ${n} ; ${name}\n`;
  idx++;
}
fs.writeFileSync('src/notes.inc', '; Generated by tools/gen_notes.js\n' + eq);
fs.writeFileSync('src/notes_tbl.inc', '; Generated by tools/gen_notes.js\n' + tbl);
