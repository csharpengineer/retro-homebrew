// Packs the speech WAVs into build/YACHT.SPK and writes src/speech.inc.
// Clips never cross a 64K bank, because the 8237 DMA page register is fixed
// for a transfer. Bank 0 starts with a table: word count, then for each clip
// word bank, word offset, word length.
const fs = require('fs');
const lines = fs.readFileSync('tools/speech.txt', 'latin1').split(/\r?\n/).filter(Boolean);
const names = lines.map(l => l.split('|')[0]);
function pcm(file) {
  const b = fs.readFileSync(file);
  let p = 12, data = null;
  while (p + 8 <= b.length) {
    const id = b.toString('latin1', p, p + 4), n = b.readUInt32LE(p + 4);
    if (id === 'data') { data = b.subarray(p + 8, p + 8 + n); break; }
    p += 8 + n + (n & 1);
  }
  if (!data) throw new Error('no data chunk in ' + file);
  let s = 0, e = data.length - 1;
  while (s < e && Math.abs(data[s] - 128) < 5) s++;
  while (e > s && Math.abs(data[e] - 128) < 5) e--;
  const t = data.subarray(Math.max(0, s - 40), Math.min(data.length, e + 120));
  let peak = 1;
  for (const v of t) peak = Math.max(peak, Math.abs(v - 128));
  const g = 120 / peak, out = Buffer.alloc(t.length);
  for (let i = 0; i < t.length; i++) out[i] = Math.max(0, Math.min(255, Math.round(128 + (t[i] - 128) * g)));
  return out;
}
const HDR = 256, BANK = 65536;
const clips = names.map(n => pcm(`build/speech/${n}.wav`));
const banks = [Buffer.alloc(BANK, 128), Buffer.alloc(BANK, 128)];
const pos = [HDR, 0], table = [];
let bank = 0;
clips.forEach((c, i) => {
  if (pos[bank] + c.length > BANK) bank++;
  if (bank > 1) throw new Error('speech does not fit in two banks');
  c.copy(banks[bank], pos[bank]);
  table.push([bank, pos[bank], c.length]);
  pos[bank] += c.length;
});
banks[0].writeUInt16LE(clips.length, 0);
table.forEach((t, i) => t.forEach((v, j) => banks[0].writeUInt16LE(v, 2 + i * 6 + j * 2)));
const used = bank === 0 ? banks[0].subarray(0, pos[0]) : Buffer.concat([banks[0], banks[1].subarray(0, pos[1])]);
fs.writeFileSync('build/YACHT.SPK', used);
fs.writeFileSync('src/speech.inc', '; Generated by tools/mkspk.js\n' +
  names.map((n, i) => `SPK_${n.toUpperCase()} equ ${i}`).join('\n') + '\n');
console.log('speech', used.length, 'bytes,', clips.length, 'clips,', (clips.reduce((a, c) => a + c.length, 0) / 8008).toFixed(1), 'seconds');
