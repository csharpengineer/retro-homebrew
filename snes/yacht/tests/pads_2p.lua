-- port2: pad
-- Two players with both controllers plugged in: each controller plays only its own turns.
function test()
  set_limit(20000)
  start_game(1)
  wait_human()
  check(v8("cur") == 0, "player 1 doesn't start")
  press(2, { "a" }, 2)
  press(2, { "x" }, 2)
  wait(10)
  check(v8("rolls_left") == 3, "controller 2 rolled on player 1's turn")
  press(1, { "a" }, 2)
  wait_human()
  check(v8("rolls_left") == 2, "controller 1 couldn't roll on player 1's turn")
  press(1, { "down" }, 2)
  press(1, { "a" }, 2)
  wait_until(function() return v8("cur") == 1 end, 300, "player 2's turn")
  wait_human()
  press(1, { "a" }, 2)
  press(1, { "x" }, 2)
  wait(10)
  check(v8("rolls_left") == 3, "controller 1 rolled on player 2's turn")
  press(2, { "a" }, 2)
  wait_human()
  check(v8("rolls_left") == 2, "controller 2 couldn't roll on player 2's turn")
  press(2, { "down" }, 2)
  press(2, { "a" }, 2)
  wait_until(function() return v8("cur") == 0 end, 300, "back to player 1")
end
