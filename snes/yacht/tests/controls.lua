-- Dice controls: A rolls the first time, then A holds or releases the die under
-- the cursor and only X rolls again. With rolls left, the scorecard says B goes back.
function test()
  set_limit(20000)
  start_game(0)
  wait_human()
  check(screen_has("TO ROLL"), "no roll prompt at the start of the turn")
  press(1, { "a" }, 2)
  wait_human()
  check(v8("rolls_left") == 2, "A didn't make the first roll")
  check(screen_has("A: HOLD") and screen_has("X: ROLL"), "status doesn't say A holds and X rolls")
  local held = addr("held")
  press(1, { "a" }, 2)
  wait(4)
  check(read8(held) == 1, "A didn't hold the first die")
  check(v8("rolls_left") == 2, "A rolled again instead of holding")
  press(1, { "a" }, 2)
  check(read8(held) == 0, "A again didn't release it")
  press(1, { "right" }, 2)
  press(1, { "a" }, 2)
  check(read8(held + 1) == 1, "A didn't hold the second die")
  local kept = dice_now()[2]
  press(1, { "x" }, 2)
  wait_human()
  check(v8("rolls_left") == 1, "X didn't roll")
  check(dice_now()[2] == kept and read8(held + 1) == 1, "the held die changed")
  -- to the scorecard with a roll left: B is offered as the way back
  press(1, { "down" }, 2)
  check(v8("focus") == 1, "Down didn't move to the scorecard")
  check(screen_has("B: BACK"), "the scorecard doesn't say B goes back")
  wait(4)
  shot("controls_card")
  press(1, { "b" }, 2)
  check(v8("focus") == 0, "B didn't go back to the dice")
  press(1, { "x" }, 2)
  wait_human()
  check(v8("rolls_left") == 0 and v8("focus") == 1, "last roll didn't move to the scorecard")
  check(not screen_has("B: BACK"), "B: BACK shown with no rolls left")
end
