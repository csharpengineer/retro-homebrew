// Turns the rendered phrases (build/speech/*.wav) into BRR clips for the voice
// buffer: trim silence, low-pass and resample to 12 kHz, normalize, encode.
// Writes build/voice/<name>.brr and build/gfx/voice.inc. Fails if a clip won't
// fit the 16 KB buffer. With --preview, also writes build/preview/<name>.wav
// decoded back from the BRR, to check levels.
const fs = require('fs');
const path = require('path');
const brr = require('./brr');
const speechLines = require('./speech_lines');

const ROOT = path.join(__dirname, '..');
const RATE = 12000, BUFFER = 16384, PEAK = 0.85 * 32767;
const order = speechLines().map((l) => l.name);

function readWav(file) {
  const b = fs.readFileSync(file);
  let p = 12, rate = 0, bits = 0, data = null;
  while (p + 8 <= b.length) {
    const id = b.toString('latin1', p, p + 4), size = b.readUInt32LE(p + 4);
    if (id === 'fmt ') { rate = b.readUInt32LE(p + 12); bits = b.readUInt16LE(p + 22); }
    if (id === 'data') data = b.subarray(p + 8, p + 8 + size);
    p += 8 + size + (size & 1);
  }
  if (bits !== 16 || !data) throw new Error(`${file}: need 16-bit PCM`);
  const s = new Float64Array(data.length / 2);
  for (let i = 0; i < s.length; i++) s[i] = data.readInt16LE(i * 2);
  return { rate, s };
}

function writeWav(file, rate, int16) {
  const b = Buffer.alloc(44 + int16.length * 2);
  b.write('RIFF', 0, 'latin1'); b.writeUInt32LE(36 + int16.length * 2, 4); b.write('WAVEfmt ', 8, 'latin1');
  b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22); b.writeUInt32LE(rate, 24);
  b.writeUInt32LE(rate * 2, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34);
  b.write('data', 36, 'latin1'); b.writeUInt32LE(int16.length * 2, 40);
  int16.forEach((v, i) => b.writeInt16LE(v, 44 + i * 2));
  fs.writeFileSync(file, b);
}

// Windowed-sinc resampler with its cutoff below the new Nyquist (anti-aliasing).
function resample(s, from, to) {
  const ratio = from / to, n = Math.floor(s.length / ratio), out = new Float64Array(n);
  const fc = 0.45 / Math.max(ratio, 1), half = 16;
  for (let i = 0; i < n; i++) {
    const c = i * ratio;
    let acc = 0, wsum = 0;
    for (let k = Math.floor(c) - half * Math.ceil(ratio); k <= Math.ceil(c) + half * Math.ceil(ratio); k++) {
      if (k < 0 || k >= s.length) continue;
      const x = k - c;
      const sinc = x === 0 ? 2 * fc : Math.sin(2 * Math.PI * fc * x) / (Math.PI * x);
      const win = 0.5 + 0.5 * Math.cos((Math.PI * x) / (half * Math.ceil(ratio) + 1));
      acc += s[k] * sinc * win;
      wsum += sinc * win;
    }
    out[i] = wsum ? acc / wsum : 0;
  }
  return out;
}

function trim(s, thresh = 300) {
  let a = 0, b = s.length - 1;
  while (a < b && Math.abs(s[a]) < thresh) a++;
  while (b > a && Math.abs(s[b]) < thresh) b--;
  return s.subarray(Math.max(0, a - 200), Math.min(s.length, b + 400));
}

const preview = process.argv.includes('--preview');
fs.mkdirSync(path.join(ROOT, 'build/voice'), { recursive: true });
fs.mkdirSync(path.join(ROOT, 'build/preview'), { recursive: true });
let inc = 'VoiceClips:   ; address, bank, length per clip (order of speech.txt)\n';
let sections = '';
for (const name of order) {
  const { rate, s } = readWav(path.join(ROOT, 'build/speech', name + '.wav'));
  let v = resample(trim(s), rate, RATE);
  let peak = 0;
  for (const x of v) peak = Math.max(peak, Math.abs(x));
  const k = PEAK / (peak || 1);
  // fade the last 10 ms so the clip ends without a click
  const fade = Math.round(RATE * 0.01);
  const pcm = Int16Array.from(v, (x, i) => Math.round(x * k * Math.min(1, (v.length - 1 - i) / fade)));
  const enc = brr.encode(pcm);
  if (enc.length > BUFFER) throw new Error(`voice clip ${name} is ${enc.length} bytes, over ${BUFFER}`);
  fs.writeFileSync(path.join(ROOT, 'build/voice', name + '.brr'), enc);
  const label = 'Clip_' + name;
  inc += `  .dw ${label}\n  .db :${label}\n  .dw ${enc.length}\n`;
  sections += `.SECTION "${label}" SUPERFREE\n${label}:\n  .INCBIN "build/voice/${name}.brr"\n.ENDS\n`;
  if (preview) writeWav(path.join(ROOT, 'build/preview', name + '.wav'), RATE, brr.decode(enc));
  console.log(`voice: ${name} ${(pcm.length / RATE).toFixed(2)} s, ${enc.length} bytes`);
}
fs.writeFileSync(path.join(ROOT, 'build/gfx/voice.inc'), '; generated by tools/voice.js\n' + inc);
fs.writeFileSync(path.join(ROOT, 'build/gfx/voice_data.inc'), '; generated by tools/voice.js\n' + sections);
