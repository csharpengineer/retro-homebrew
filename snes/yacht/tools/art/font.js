// Index grid for one glyph: 3 = upper body, 2 = lower body, 1 = shadow.
function glyph(ch) {
  const idx = new Uint8Array(64);
  const rows = (G[ch] || G[' ']).split('/');
  const on = (x, y) => y >= 0 && y < rows.length && x >= 0 && x < 5 && rows[y][x] === '#';
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      const gx = x - 1, gy = y;
      if (on(gx, gy)) idx[y * 8 + x] = gy < 3 ? 3 : 2;
      else if (on(gx - 1, gy - 1)) idx[y * 8 + x] = 1;
    }
  }
  return idx;
}

// Eight text palettes: [shadow, lower body, upper body].
const PALS = [
  ['#1a1020', '#e8d8b0', '#fff8e8'], // 0 cream
  ['#2a1400', '#f0a020', '#ffe070'], // 1 gold
  ['#200008', '#d84838', '#ff9078'], // 2 red: score previews
  ['#001428', '#48b4e8', '#b0f0ff'], // 3 sea blue
  ['#d8c49c', '#a82418', '#cc4026'], // 4 red ink on parchment: score previews
  ['#001808', '#40c060', '#a8ffa8'], // 5 green
  ['#d8c49c', '#3a2410', '#5a3a1a'], // 6 ink on parchment (light shadow)
  ['#000000', '#c8c8d8', '#ffffff'], // 7 white
];

const out = path.join(__dirname, '../../build');
fs.mkdirSync(path.join(out, 'gfx'), { recursive: true });
fs.mkdirSync(path.join(out, 'preview'), { recursive: true });

const tiles = [];
for (let c = 32; c < 128; c++) tiles.push(gfx.encodeTile(glyph(String.fromCharCode(c)), 2));
fs.writeFileSync(path.join(out, 'gfx/font.bin'), Buffer.concat(tiles));

const cols = [];
for (const p of PALS) cols.push([0, 0, 0], hex(p[0]), hex(p[1]), hex(p[2]));
fs.writeFileSync(path.join(out, 'gfx/textpal.bin'), gfx.paletteBytes(cols, 32));

// Preview: every glyph in each palette on a mid-blue backdrop, 2x scale.
const W = 16 * 8, H = 6 * 8 * PALS.length, S = 2;
const rgba = Buffer.alloc(W * S * H * S * 4);
for (let p = 0; p < PALS.length; p++) {
  for (let c = 32; c < 128; c++) {
    const g = glyph(String.fromCharCode(c)), n = c - 32;
    const ox = (n % 16) * 8, oy = p * 48 + Math.floor(n / 16) * 8;
    for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) {
      const v = g[y * 8 + x];
      const col = v ? hex(PALS[p][v - 1]) : [40, 60, 110, 255];
      for (let sy = 0; sy < S; sy++) for (let sx = 0; sx < S; sx++) {
        const i = (((oy + y) * S + sy) * W * S + (ox + x) * S + sx) * 4;
        rgba[i] = col[0]; rgba[i + 1] = col[1]; rgba[i + 2] = col[2]; rgba[i + 3] = 255;
      }
    }
  }
}
png.write(path.join(out, 'preview/font.png'), W * S, H * S, rgba);
