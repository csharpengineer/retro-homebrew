// Shared helpers for the art scripts: output files, sprite sheets, metasprite
// tables, HDMA tables and previews that show the art as the SNES will.
const fs = require('fs');
const path = require('path');
const gfx = require('../snesgfx');
const png = require('../png');
const { Raster } = require('../raster');

const OUT = path.join(__dirname, '../../build');
fs.mkdirSync(path.join(OUT, 'gfx'), { recursive: true });
fs.mkdirSync(path.join(OUT, 'preview'), { recursive: true });

function writeBin(name, buf) { fs.writeFileSync(path.join(OUT, 'gfx', name), buf); }
function writeInc(name, text) { fs.writeFileSync(path.join(OUT, 'gfx', name), '; generated by snes/tools/art\n' + text); }
function previewPng(name, r) { png.write(path.join(OUT, 'preview', name), r.w, r.h, Buffer.from(r.data.buffer)); }

// Replaces every pixel by its palette color (or transparent), so previews show
// the exact colors that reach the screen.
function quantized(r, pal) {
  const q = new Raster(r.w, r.h);
  for (let y = 0; y < r.h; y++) for (let x = 0; x < r.w; x++) {
    const i = gfx.indexOf(r.get(x, y), pal);
    if (i) q.set(x, y, [...pal[i], 255]);
  }
  return q;
}

// Ordered-dither a raster toward a palette (4x4 Bayer). Keeps alpha.
const BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
function dither(r, strength = 10) {
  const o = new Raster(r.w, r.h);
  for (let y = 0; y < r.h; y++) for (let x = 0; x < r.w; x++) {
    const c = r.get(x, y);
    const d = (BAYER[(y & 3) * 4 + (x & 3)] / 15 - 0.5) * strength;
    o.set(x, y, [c[0] + d, c[1] + d, c[2] + d, c[3]]);
  }
  return o;
}

// A 16-tile-wide sprite VRAM sheet. add() places a 16x16 or 32x32 cell and
// returns its first tile number.
class SpriteSheet {
  constructor(rows = 32) {
    this.rows = rows;
    this.used = Array.from({ length: rows }, () => new Array(16).fill(false));
    this.tiles = new Map();
  }
  alloc(size) {
    const n = size / 8;
    for (let r = 0; r + n <= this.rows; r++)
      for (let c = 0; c + n <= 16; c++) {
        let ok = true;
        for (let y = 0; y < n && ok; y++) for (let x = 0; x < n && ok; x++) if (this.used[r + y][c + x]) ok = false;
        if (ok) {
          for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) this.used[r + y][c + x] = true;
          return r * 16 + c;
        }
      }
    throw new Error('sprite sheet full');
  }
  // r: raster holding the art; (sx, sy) its top-left; pal: 16 colors.
  add(r, sx, sy, size, pal) {
    const base = this.alloc(size), n = size / 8;
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      this.tiles.set(base + y * 16 + x, gfx.encodeTile(gfx.tileIndices(r, pal, sx + x * 8, sy + y * 8), 4));
    }
    return base;
  }
  bytes() {
    let last = 0;
    for (const k of this.tiles.keys()) last = Math.max(last, k);
    const rowsUsed = Math.floor(last / 16) + 1;
    const out = [];
    for (let i = 0; i < rowsUsed * 16; i++) out.push(this.tiles.get(i) || Buffer.alloc(32));
    return Buffer.concat(out);
  }
}

// Cuts a raster into 32x32 (or 16x16) sprites, skipping empty cells. Returns a
// metasprite: [{dx, dy, tile, big}].
function cutMeta(sheet, r, pal, size, ox = 0, oy = 0) {
  const parts = [];
  for (let y = 0; y < r.h; y += size) for (let x = 0; x < r.w; x += size) {
    let any = false;
    for (let yy = y; yy < Math.min(r.h, y + size) && !any; yy++)
      for (let xx = x; xx < Math.min(r.w, x + size) && !any; xx++) if (gfx.indexOf(r.get(xx, yy), pal)) any = true;
    if (!any) continue;
    parts.push({ dx: x - ox, dy: y - oy, tile: sheet.add(r, x, y, size, pal), big: size === 32 });
  }
  return parts;
}

// Metasprite as assembler data: count, then dx, dy, tile, attr-palette, size.
function metaAsm(label, parts, palNum, prio = 3) {
  let s = `${label}:\n  .db ${parts.length}\n`;
  for (const p of parts) {
    const attr = (prio << 4) | (palNum << 1) | ((p.tile >> 8) & 1);
    s += `  .db ${p.dx & 255}, ${p.dy & 255}, ${p.tile & 255}, ${attr}, ${p.big ? 1 : 0}\n`;
  }
  return s;
}

// HDMA table writing one color per scanline to CGRAM entry `index` (mode 3 on $2121).
function colorGradientHdma(colors, index = 0) {
  const out = [];
  let i = 0;
  while (i < colors.length) {
    const n = Math.min(127, colors.length - i);
    out.push(0x80 | n);
    for (let k = 0; k < n; k++) {
      const c = gfx.toBGR555(...colors[i + k]);
      out.push(index, index, c & 255, c >> 8);
    }
    i += n;
  }
  out.push(0);
  return Buffer.from(out);
}

function scale(r, k) {
  const o = new Raster(r.w * k, r.h * k);
  for (let y = 0; y < o.h; y++) for (let x = 0; x < o.w; x++) o.set(x, y, r.get(Math.floor(x / k), Math.floor(y / k)));
  return o;
}

module.exports = { scale, OUT, writeBin, writeInc, previewPng, quantized, dither, SpriteSheet, cutMeta, metaAsm, colorGradientHdma };
