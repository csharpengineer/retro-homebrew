// The game screen backdrop (320x240): a captain's table of dark wood, the
// parchment scorecard on the left, the felt dice tray and three navy-and-brass
// plaques (turn banner, rolls left, status) on the right. Writes
// build/assets/game_bg.png and build/gen/layout.h, so the code draws its text
// and dice exactly where the art leaves room for them.
const path = require('path');
const fs = require('fs');
const { Raster, mix, hex } = require('../lib').raster;
const { writePng, preview, noise, ASSETS, GEN } = require('../lib');

const W = 320, H = 240;
const CARD = { x: 10, y: 10, w: 142, h: 220 };
const ROW0 = 32, ROWH = 14, TOTAL_Y = 204;            // 12 box rows, then the total row
const RULE_L = 97, RULE_M = 125;                      // column rules: names | P1 | P2
const BANNER = { x: 158, y: 10, w: 152, h: 26 };
const TRAY = { x: 158, y: 40, w: 152, h: 112 };
const ROLLS = { x: 158, y: 156, w: 152, h: 22 };
const STATUS = { x: 158, y: 182, w: 152, h: 48 };
// dice rest positions (centres), three over two like the SNES tray
const DIE_X = [194, 234, 274, 214, 254], DIE_Y = [78, 78, 78, 120, 120];

const r = new Raster(W, H);

// wood: horizontal planks with grain and seams
const PLANK = 30;
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  const p = Math.floor(y / PLANK), yy = y % PLANK;
  const grain = noise(x * 0.25 + p * 97, y * 3, 6, 3 + p) * 0.6 + noise(x, y, 40, 9 + p) * 0.4;
  let c = mix(hex('#3a1c0e'), hex('#6a3a1c'), grain);
  c = mix(c, hex('#24100a'), yy === 0 ? 0.8 : yy === 1 ? 0.35 : 0);
  r.set(x, y, c);
}
// a soft vignette toward the corners
r.shade((x, y) => 1 - 0.35 * Math.min(1, Math.hypot((x - W / 2) / (W / 2), (y - H / 2) / (H / 2)) ** 2));

function dropShadow(b, d = 3, rad = 4) {
  for (let i = 3; i >= 1; i--) r.roundRect(b.x + d - i + 1, b.y + d - i + 1, b.w + 2 * i - 2, b.h + 2 * i - 2, rad + i, [0, 0, 0, 40]);
}

// scorecard: parchment with a double brown border and ruled rows
dropShadow(CARD, 4, 4);
r.roundRect(CARD.x, CARD.y, CARD.w, CARD.h, 4, (x, y) => {
  const n = noise(x, y, 7, 21) * 0.5 + noise(x, y, 31, 22) * 0.5;
  const edge = Math.min(x - CARD.x, CARD.x + CARD.w - x, y - CARD.y, CARD.y + CARD.h - y);
  return mix(mix(hex('#f4e6c4'), hex('#e2cc9c'), n), hex('#c09a62'), Math.max(0, 1 - edge / 9) * 0.55);
});
const INK = hex('#6a4424'), INK_LIGHT = hex('#6a4424', 110);
r.rect(CARD.x + 3, CARD.y + 3, CARD.w - 6, 1, INK);
r.rect(CARD.x + 3, CARD.y + CARD.h - 4, CARD.w - 6, 1, INK);
r.rect(CARD.x + 3, CARD.y + 3, 1, CARD.h - 6, INK);
r.rect(CARD.x + CARD.w - 4, CARD.y + 3, 1, CARD.h - 6, INK);
for (let i = 0; i < 12; i++) {
  const y = ROW0 + i * ROWH;
  if (i % 2) r.rect(CARD.x + 5, y, CARD.w - 10, ROWH, hex('#a07840', 22));
  r.rect(CARD.x + 5, y + ROWH - 1, CARD.w - 10, 1, i === 5 ? INK : INK_LIGHT);
}
r.rect(CARD.x + 5, ROW0 - 2, CARD.w - 10, 1, INK);
r.rect(CARD.x + 5, TOTAL_Y - 3, CARD.w - 10, 1, INK);
r.rect(CARD.x + 5, TOTAL_Y - 1, CARD.w - 10, 1, INK);
r.rect(RULE_L, CARD.y + 6, 1, CARD.h - 12, INK_LIGHT);
r.rect(RULE_M, CARD.y + 6, 1, CARD.h - 12, INK_LIGHT);

// brass-edged navy plaque
function plaque(b) {
  dropShadow(b, 3, 4);
  r.roundRect(b.x, b.y, b.w, b.h, 4, (x, y) => mix(hex('#f6d68a'), hex('#9a6a24'), (y - b.y) / b.h));
  r.roundRect(b.x + 2, b.y + 2, b.w - 4, b.h - 4, 3, (x, y) =>
    mix(hex('#26346a'), hex('#141c40'), (y - b.y) / b.h + (noise(x, y, 9, 5) - 0.5) * 0.15));
  r.rect(b.x + 4, b.y + 3, b.w - 8, 1, hex('#ffffff', 28));
}
plaque(BANNER);
plaque(ROLLS);
plaque(STATUS);

// dice tray: a polished wood rim round green felt
dropShadow(TRAY, 4, 6);
r.roundRect(TRAY.x, TRAY.y, TRAY.w, TRAY.h, 6, (x, y) => {
  const g = noise(x * 0.3, y * 2, 5, 41);
  return mix(mix(hex('#8a4e22'), hex('#b8743a'), g), hex('#2a1206'), (y - TRAY.y) / TRAY.h * 0.5);
});
const FELT = { x: TRAY.x + 6, y: TRAY.y + 6, w: TRAY.w - 12, h: TRAY.h - 12 };
r.roundRect(FELT.x, FELT.y, FELT.w, FELT.h, 4, (x, y) => {
  const n = noise(x, y, 2, 61) * 0.5 + noise(x, y, 23, 62) * 0.5;
  // lit from the top left, with the rim's shadow along the top and left edges
  const lit = 1 - 0.35 * ((x - FELT.x) / FELT.w * 0.5 + (y - FELT.y) / FELT.h * 0.5);
  const inner = Math.min(x - FELT.x, y - FELT.y);
  const c = mix(hex('#1e7a44'), hex('#2a9656'), n);
  return mix(c.map((v, i) => (i < 3 ? v * lit : v)), hex('#0a2a14'), Math.max(0, 1 - inner / 6) * 0.6);
});

writePng(path.join(ASSETS, 'game_bg.png'), r);
preview('game_bg', r, 2);

const def = (n, v) => `#define ${n} ${v}\n`;
const box = (n, b) => def(n + '_X', b.x) + def(n + '_Y', b.y) + def(n + '_W', b.w) + def(n + '_H', b.h);
fs.writeFileSync(path.join(GEN, 'layout.h'), '// generated by tools/art/game.js: where game_bg.png leaves room\n#pragma once\n' +
  box('CARD', CARD) + def('CARD_ROW0', ROW0) + def('CARD_ROWH', ROWH) + def('CARD_TOTAL_Y', TOTAL_Y) +
  def('CARD_RULE_L', RULE_L) + def('CARD_RULE_M', RULE_M) +
  box('BANNER', BANNER) + box('TRAY', TRAY) + box('FELT', FELT) + box('ROLLS', ROLLS) + box('STATUS', STATUS) +
  `static const short DIE_X[5] = { ${DIE_X.join(', ')} };\nstatic const short DIE_Y[5] = { ${DIE_Y.join(', ')} };\n`);
