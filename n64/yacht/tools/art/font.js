// The two text fonts, drawn from the SNES 5x7 glyph shapes (snes/yacht/tools/art/
// font.js) as smooth round-stroked letters at N64 resolution: each lit cell of
// the glyph is a dot, and neighbouring dots are joined by strokes.
// Writes white-on-transparent atlases (ASCII 32-126, 16 per row) that the game
// tints as it draws, plus src/gen/font.h with the cell sizes.
const path = require('path');
const fs = require('fs');
const { Raster } = require('../lib').raster;
const { writePng, preview, ASSETS, GEN } = require('../lib');

// The SNES glyph table, read from its source so the two ports share one set.
const src = fs.readFileSync(path.join(__dirname, '../../../../snes/yacht/tools/art/font.js'), 'utf8');
const G = {};
for (const m of src.matchAll(/^\s*(?:'(.)'|"(.)"|(\w)):\s*'([.#/]+)'/gm)) G[m[1] || m[2] || m[3]] = m[4];

// Draws one glyph at (ox, oy) with cell pitch s and stroke width w: the union
// of round-capped strokes between neighbouring lit cells, as one shape.
function drawGlyph(r, ch, ox, oy, s, w) {
  const rows = (G[ch] || "").split("/");
  const on = (x, y) => y >= 0 && y < rows.length && x >= 0 && x < 5 && rows[y][x] === "#";
  const px = (x) => ox + (x + 0.5) * s, py = (y) => oy + (y + 0.5) * s;
  const segs = [];
  for (let y = 0; y < rows.length; y++) for (let x = 0; x < 5; x++) {
    if (!on(x, y)) continue;
    segs.push([px(x), py(y), px(x), py(y)]);
    if (on(x + 1, y)) segs.push([px(x), py(y), px(x + 1), py(y)]);
    if (on(x, y + 1)) segs.push([px(x), py(y), px(x), py(y + 1)]);
    // diagonals only where no square corner already joins the two
    if (on(x + 1, y + 1) && !on(x + 1, y) && !on(x, y + 1)) segs.push([px(x), py(y), px(x + 1), py(y + 1)]);
    if (on(x - 1, y + 1) && !on(x - 1, y) && !on(x, y + 1)) segs.push([px(x), py(y), px(x - 1), py(y + 1)]);
  }
  if (!segs.length) return;
  const hw2 = (w / 2) ** 2;
  const inside = (qx, qy) => segs.some(([x0, y0, x1, y1]) => {
    const dx = x1 - x0, dy = y1 - y0, l2 = dx * dx + dy * dy;
    const t = l2 ? Math.max(0, Math.min(1, ((qx - x0) * dx + (qy - y0) * dy) / l2)) : 0;
    return (qx - x0 - t * dx) ** 2 + (qy - y0 - t * dy) ** 2 <= hw2;
  });
  r.shape(ox, oy, ox + 6 * s, oy + 9 * s, inside, [255, 255, 255, 255]);
}

// cell: atlas cell size; s: pixels per glyph cell; w: stroke width; pad: left/top inset
function atlas(name, cell, s, w, pad) {
  const r = new Raster(16 * cell.w, 6 * cell.h);
  for (let c = 32; c < 127; c++) {
    const n = c - 32;
    drawGlyph(r, String.fromCharCode(c), (n % 16) * cell.w + pad.x, Math.floor(n / 16) * cell.h + pad.y, s, w);
  }
  writePng(path.join(ASSETS, name + '.png'), r);
  return r;
}

const SMALL = { w: 8, h: 13, adv: 7 }, BIG = { w: 14, h: 24, adv: 13 };
const small = atlas('font_small', SMALL, 1.3, 1.25, { x: 0.4, y: 0.6 });
const big = atlas('font_big', BIG, 2.5, 2.3, { x: 0.6, y: 1 });

// Preview: sample lines in both fonts.
function sample(a, cell, lines) {
  const r = new Raster(320, lines.length * cell.h + 8);
  lines.forEach((t, li) => [...t].forEach((ch, i) => {
    const n = ch.charCodeAt(0) - 32;
    r.blit(a.crop((n % 16) * cell.w, Math.floor(n / 16) * cell.h, cell.w, cell.h), 4 + i * cell.adv, 4 + li * cell.h);
  }));
  return r;
}
preview('font_small', sample(small, SMALL, ['Ones 1  Full House 26', 'Four Alike  Small Str  Large Str', 'PICK A BOX  A: SCORE  B: BACK', 'BEST SCORE 214  V1.0  Yacht! 0123456789']), 3);
preview('font_big', sample(big, BIG, ['YOUR TURN', 'GAME OVER 213', 'SKIPPER wins']), 3);

fs.writeFileSync(path.join(GEN, 'font.h'), `// generated by tools/art/font.js
#pragma once
#define FONT_SMALL_W ${SMALL.w}
#define FONT_SMALL_H ${SMALL.h}
#define FONT_SMALL_ADV ${SMALL.adv}
#define FONT_BIG_W ${BIG.w}
#define FONT_BIG_H ${BIG.h}
#define FONT_BIG_ADV ${BIG.adv}
`);
